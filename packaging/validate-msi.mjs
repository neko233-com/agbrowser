import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, statSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const version = process.env.AGB_VERSION ?? JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).version;
const path = join(root, 'build', `agbrowser-${version}-x64.msi`);
if (!existsSync(path)) throw new Error(`MSI missing: ${path}`);
const signature = readFileSync(path).subarray(0, 8).toString('hex');
if (signature !== 'd0cf11e0a1b11ae1') throw new Error('MSI OLE signature invalid');
if (process.platform !== 'win32') throw new Error('Windows Installer table verification requires Windows');
execFileSync('powershell.exe', ['-NoProfile', '-NonInteractive', '-File', join(root, 'packaging', 'check-msi.ps1'), '-Msi', path, '-Version', version], { stdio: 'inherit' });
console.log(`PASS MSI structure; ${(statSync(path).size / 1024 / 1024).toFixed(2)} MiB. Installation is a separate check.`);
